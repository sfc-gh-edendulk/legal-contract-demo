USE ROLE SS_ADMIN_ROLE;
USE WAREHOUSE COMPUTE_WH;

CREATE SCHEMA IF NOT EXISTS LEGAL_CONTRACT_DEMO.EXPERIMENTS;

CREATE TABLE IF NOT EXISTS LEGAL_CONTRACT_DEMO.EXPERIMENTS.RUN_METADATA (
    RUN_ID VARCHAR DEFAULT UUID_STRING(),
    METHOD VARCHAR,
    MODEL VARCHAR,
    STARTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    FINISHED_AT TIMESTAMP_NTZ,
    TOTAL_WALL_TIME_SECS FLOAT,
    TOTAL_CREDITS_ESTIMATE FLOAT,
    CONTRACT_COUNT NUMBER,
    CLAUSE_COUNT NUMBER,
    NOTES VARCHAR
);

CREATE TABLE IF NOT EXISTS LEGAL_CONTRACT_DEMO.EXPERIMENTS.RUN_RESULTS (
    RUN_ID VARCHAR,
    CONTRACT_ID VARCHAR,
    STEP VARCHAR,
    WALL_TIME_MS FLOAT,
    INPUT_CHARS NUMBER,
    OUTPUT_RAW VARCHAR(16777216),
    PARSED_OUTPUT VARIANT,
    CLAUSE_COUNT NUMBER,
    ERROR VARCHAR
);

CREATE TABLE IF NOT EXISTS LEGAL_CONTRACT_DEMO.EXPERIMENTS.EVAL_METRICS (
    RUN_ID VARCHAR,
    CONTRACT_ID VARCHAR,
    METRIC_NAME VARCHAR,
    METRIC_VALUE FLOAT
);

CREATE TABLE IF NOT EXISTS LEGAL_CONTRACT_DEMO.EXPERIMENTS.CUAD_GROUND_TRUTH (
    CONTRACT_ID VARCHAR,
    FILENAME VARCHAR,
    CUAD_CATEGORY VARCHAR,
    IS_PRESENT BOOLEAN,
    ANSWER_SPANS VARIANT,
    EXPECTED_TEAM VARCHAR
);
